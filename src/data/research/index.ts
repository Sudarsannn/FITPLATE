/**
 * Research content bundled with the app (generated per-item JSON; see
 * scripts/research/run.js). It is the app's only dish content: the demo
 * dishes were removed on 22 Oct 2026.
 *
 * Priority plan P2-c: when the shared research library on the server is newer
 * than this bundle, services/researchRemote.ts swaps it in with
 * applyResearchSnapshot(). The exported arrays are replaced in place, so every
 * import sees the new content; the bundle stays the offline fallback.
 */
import type { Dish, Ingredient } from '../../models/research';
import type { Exercise, Guidance as FitnessGuide } from '../../models/exercise';
import type { Guidance, HealthCondition, Hydration, Nutrient } from '../../models/nutrient';
import { items as dishItems } from './dishes';
import { items as ingredientItems } from './ingredients';
import { items as nutrientItems } from './nutrients';
import { items as hydrationItems } from './hydration';
import { items as guidanceItems } from './guidance';
import { items as conditionItems } from './conditions';
import { items as exerciseItems } from './exercises';
import { items as fitnessGuideItems } from './fitness-guides';
import aliasData from './ingredients/aliases.json';
import ledgerData from './ledger.json';
import linkData from './links.json';
import { researchVersion } from '../../services/data/researchVersion';

const dishList: Dish[] = [...dishItems];
const ingredientList: Ingredient[] = [...ingredientItems];
const nutrientList: Nutrient[] = [...nutrientItems];
const hydrationList: Hydration[] = [...hydrationItems];
const guidanceList: Guidance[] = [...guidanceItems];
const conditionList: HealthCondition[] = [...conditionItems];
const exerciseList: Exercise[] = [...exerciseItems];
const fitnessGuideList: FitnessGuide[] = [...fitnessGuideItems];

export const researchDishes: readonly Dish[] = dishList;
export const researchIngredients: readonly Ingredient[] = ingredientList;
export const researchNutrients: readonly Nutrient[] = nutrientList;
export const researchHydration: readonly Hydration[] = hydrationList;
export const researchGuidance: readonly Guidance[] = guidanceList;
export const researchConditions: readonly HealthCondition[] = conditionList;
export const researchExercises: readonly Exercise[] = exerciseList;
export const researchFitnessGuides: readonly FitnessGuide[] = fitnessGuideList;

const aliasMap: Record<string, string> = { ...aliasData };
/** F1: any spelling (slug) → canonical ingredient id. */
export const ingredientAliases: Readonly<Record<string, string>> = aliasMap;

/** Version of the research the app ships with (see researchVersion.js). */
export const BUNDLED_RESEARCH_VERSION: string = researchVersion(ledgerData);

/** Spec F cross-links generated by the runner (good-source dishes, families, drinks, MET, micronutrient table). */
export type ResearchLinks = {
  goodSourceDishes: Record<string, { dishNumber: number; dishName: string; dishId: string | null }[]>;
  dishGoodSourceOf: Record<string, string[]>;
  families: { familyId: string; dishIds: string[]; how: 'name' | 'research-variant' }[];
  met: { exerciseId: string; name: string; met: number }[];
  microTable: Record<string, Record<string, { per100: number; unit: string; source: string }>>;
};
export const researchLinks: ResearchLinks = { ...(linkData as unknown as ResearchLinks) };

const dishById = new Map(dishList.map((d) => [d.id, d]));
/** Dishes the AI created on this device (see services/ai). They sit in dishList too, so every screen finds them with getDish. */
const customDishes: Dish[] = [];
let customRev = 0;
const ingredientById = new Map(ingredientList.map((i) => [i.id, i]));

/** One full research library, as the import script writes it to the server. */
export type ResearchSnapshot = {
  version: string;
  dishes: Dish[];
  ingredients: Ingredient[];
  nutrients: Nutrient[];
  hydration: Hydration[];
  guidance: Guidance[];
  conditions: HealthCondition[];
  exercises: Exercise[];
  fitnessGuides: FitnessGuide[];
  aliases: Record<string, string>;
  links: ResearchLinks;
};

let activeVersion = BUNDLED_RESEARCH_VERSION;
let activeSource: 'bundle' | 'server' = 'bundle';
const listeners = new Set<() => void>();

const replace = <T,>(target: T[], next: T[] | undefined) => {
  if (!Array.isArray(next) || next.length === 0) return; // never empty a list because the server copy is incomplete
  target.splice(0, target.length, ...next);
};

/** Swap in a newer research library (from the server or its device cache). */
export function applyResearchSnapshot(snap: ResearchSnapshot): void {
  replace(dishList, snap.dishes);
  replace(ingredientList, snap.ingredients);
  replace(nutrientList, snap.nutrients);
  replace(hydrationList, snap.hydration);
  replace(guidanceList, snap.guidance);
  replace(conditionList, snap.conditions);
  replace(exerciseList, snap.exercises);
  replace(fitnessGuideList, snap.fitnessGuides);
  if (snap.aliases && Object.keys(snap.aliases).length) {
    for (const k of Object.keys(aliasMap)) delete aliasMap[k];
    Object.assign(aliasMap, snap.aliases);
  }
  if (snap.links) Object.assign(researchLinks, snap.links);
  // Dishes the AI created on this device stay, whichever library is in use.
  for (const d of customDishes) if (!dishList.some((x) => x.id === d.id)) dishList.push(d);
  dishById.clear();
  for (const d of dishList) dishById.set(d.id, d);
  ingredientById.clear();
  for (const i of ingredientList) ingredientById.set(i.id, i);
  activeVersion = snap.version;
  activeSource = 'server';
  listeners.forEach((l) => l());
}

/** Which research library is in use. */
export function researchInfo(): { version: string; source: 'bundle' | 'server' } {
  return { version: activeVersion, source: activeSource };
}

/** Called after applyResearchSnapshot, so screens can re-read the lists. */
export function onResearchChange(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** An AI dish id that the researched dish has since replaced, so old logs, favourites and plans still open. */
const idAliases = new Map<string, string>();
export function aliasDish(from: string, to: string): void {
  idAliases.set(from, to);
}

export function getDish(id: string): Dish | undefined {
  return dishById.get(id) ?? dishById.get(idAliases.get(id) ?? '');
}

export function getIngredient(id: string): Ingredient | undefined {
  return ingredientById.get(id);
}

/** Other dishes in the same variant family (e.g. Veg and Chicken Biryani). */
export function familyOf(dish: Dish): Dish[] {
  if (!dish.familyId) return [];
  return dishList.filter((d) => d.familyId === dish.familyId && d.id !== dish.id);
}

/** Add (or replace) a dish the AI created. Screens re-read the lists through onResearchChange. */
export function registerCustomDish(dish: Dish): void {
  const at = customDishes.findIndex((d) => d.id === dish.id);
  if (at >= 0) customDishes[at] = dish;
  else customDishes.push(dish);
  const inList = dishList.findIndex((d) => d.id === dish.id);
  if (inList >= 0) dishList[inList] = dish;
  else dishList.push(dish);
  dishById.set(dish.id, dish);
  customRev++;
  listeners.forEach((l) => l());
}

export function removeCustomDish(id: string): void {
  const at = customDishes.findIndex((d) => d.id === id);
  if (at < 0) return;
  customDishes.splice(at, 1);
  const inList = dishList.findIndex((d) => d.id === id);
  if (inList >= 0) dishList.splice(inList, 1);
  dishById.delete(id);
  customRev++;
  listeners.forEach((l) => l());
}

export function getCustomDishes(): readonly Dish[] {
  return customDishes;
}

/** Changes whenever an AI dish is added or removed; screens use it to recompute lists. */
export function customRevision(): number {
  return customRev;
}
